// keyed by the *old* Monster-Manual-derived display name (matches js/monsters.json's
// pre-migration array). Used once by scripts/migrate-to-registry.js to build the new
// id-keyed registry — see that file for how `id` is derived (slugify(name), not hand-picked).
//
// category is a single 5e SRD creature type (Aberration, Beast, Celestial, Construct,
// Dragon, Elemental, Fey, Fiend, Giant, Humanoid, Monstrosity, Ooze, Plant, Undead).
// tags are free-text search keywords (subtype/faction, element, role, terrain, etc.) —
// assigned from general 5e Monster Manual knowledge as a best-effort pass; spot-check
// before relying on them for anything beyond in-site search/filtering.
//
// slugify() is also exported so migrate-to-registry.js and any future one-off script
// derive ids the same way instead of copy-pasting the regex.
function slugify(name) {
  return name
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

