// Regenerates js/vault-data.js from js/monsters.json (the id-keyed monster registry —
// name/category/tags, hand-maintained) plus whatever's actually present in
// images-optimized/<Style>/ (falls back to images/<Style>/ if optimize hasn't run yet).
//
// Unlike the old tokens.js (one array per style), vault-data.js is monster-primary:
// one entry per monster, with a `filenames` object nested inside holding the file for
// each style (or null if that style doesn't have art for this monster yet). That makes
// "does every monster have a version in every style" a property you can see on a single
// entry instead of cross-referencing parallel per-style arrays — see checkCoverage().
//
// Run: npm run vault-data

const fs = require("fs");
const path = require("path");
const { getAllowedStyles, folderNameForStyle } = require("./lib/styles");
const { slugify } = require("./lib/slug");

const ROOT_DIR = path.join(__dirname, "..");
const OPTIMIZED_DIR = path.join(ROOT_DIR, "images-optimized");
const FALLBACK_DIR = path.join(ROOT_DIR, "images");
const OUT_FILE = path.join(ROOT_DIR, "js", "vault-data.js");
const MONSTERS_FILE = path.join(ROOT_DIR, "js", "monsters.json");
const IMG_RE = /\.(webp|png|jpe?g)$/i;

function loadRegistry() {
  const registry = JSON.parse(fs.readFileSync(MONSTERS_FILE, "utf8"));
  if (Array.isArray(registry)) {
    throw new Error(`${path.relative(ROOT_DIR, MONSTERS_FILE)} should be an id-keyed object, not an array.`);
  }
  return registry;
}

// Returns { style, files: Map<id, filename>, source: "images-optimized/Standard" | null }
function idsForStyle(style) {
  const folder = folderNameForStyle(style);
  const optimizedDir = path.join(OPTIMIZED_DIR, folder);
  const fallbackDir = path.join(FALLBACK_DIR, folder);
  const dir = fs.existsSync(optimizedDir) ? optimizedDir : fallbackDir;

  if (!fs.existsSync(dir)) {
    return { style, files: new Map(), source: null };
  }

  // Files are named after the monster's display name (e.g. "Angel -
  // Ascendant.webp"), not its id — slugify() derives the id the same way
  // monsters.json's ids are derived from their names (see
  // validate-monsters.js), so a file matches a registry entry exactly when
  // its slugified name equals that entry's id.
  const files = new Map();
  fs.readdirSync(dir)
    .filter((f) => IMG_RE.test(f))
    .forEach((f) => files.set(slugify(f.replace(IMG_RE, "")), f));

  return { style, files, source: path.relative(ROOT_DIR, dir) };
}

// Warn-only: flags monsters missing art for a style that's actually been started, and
// stray files that don't match any registry id (typo, leftover from a rename, removed monster).
function checkCoverage(registry, results) {
  const registryIds = Object.keys(registry);
  const presentStyles = results.filter((r) => r.source);
  if (presentStyles.length === 0) return;

  console.log(`\nChecking ${registryIds.length} monsters from ${path.relative(ROOT_DIR, MONSTERS_FILE)} against image folders...`);

  let anyIssues = false;
  for (const { style, files, source } of presentStyles) {
    const missing = registryIds.filter((id) => !files.has(id)).sort((a, b) => a.localeCompare(b));
    const extra = [...files.keys()].filter((id) => !registry[id]).sort((a, b) => a.localeCompare(b));

    if (missing.length === 0 && extra.length === 0) continue;
    anyIssues = true;

    console.log(`\n  ${style} (${source}/):`);
    if (missing.length > 0) {
      console.log(`    Missing ${missing.length} monster(s):`);
      missing.forEach((id) => console.log(`      - ${id} (${registry[id].name})`));
    }
    if (extra.length > 0) {
      console.log(`    ${extra.length} file(s) not in the registry (typo, rename, or removed monster?):`);
      extra.forEach((id) => console.log(`      - ${files.get(id)}`));
    }
  }

  console.log(anyIssues ? "\nCoverage check found mismatches (see above)." : "\nAll checked style folders match the registry.");
}

function main() {
  const registry = loadRegistry();
  const styles = getAllowedStyles();
  const results = styles.map(idsForStyle);

  const registryIds = Object.keys(registry).sort((a, b) => a.localeCompare(b));

  const entries = registryIds.map((id) => {
    const { name, category, tags } = registry[id];
    const filenames = {};
    results.forEach(({ style, files }) => {
      filenames[style] = files.has(id) ? files.get(id) : null;
    });
    return `  { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, category: ${JSON.stringify(category)}, tags: ${JSON.stringify(tags)}, filenames: ${JSON.stringify(filenames)} },`;
  }).join("\n");

  const contents = `// Generated by scripts/generate-vault-data.js — do not edit by hand.
// One entry per monster (see js/monsters.json for the hand-maintained name/category/tags
// source). filenames holds the art file for each style in VAULT_STYLES, or null if that
// style doesn't have art for this monster yet. Add or remove images in
// images-optimized/<Style>/ (or images/<Style>/ before running npm run optimize), then
// run: npm run vault-data
const VAULT_STYLES = ${JSON.stringify(styles)};

const VAULT_DATA = [
${entries}
];
`;

  fs.writeFileSync(OUT_FILE, contents);

  results.forEach(({ style, files, source }) => {
    const sourceNote = source ? `source: ${source}/` : "no folder found yet";
    const count = registryIds.filter((id) => files.has(id)).length;
    console.log(`${style}: ${count} of ${registryIds.length} monsters have art (${sourceNote})`);
  });
  console.log(`\nWrote ${OUT_FILE}`);

  checkCoverage(registry, results);
}

main();
