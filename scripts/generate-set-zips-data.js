// Regenerates js/set-zips-data.js by scanning zips/<Style>/ for the *-hires.zip /
// *-lowres.zip files written by build-set-zips.js. Run this after build-zips whenever
// the zips change, so sets.html has up-to-date filenames/sizes/counts to render
// download buttons from without hitting the network.
//
// Run: npm run set-zips-data

const fs = require("fs");
const path = require("path");
const { getAllowedStyles, folderNameForStyle } = require("./lib/styles");
const { readEntryCount } = require("./lib/zip-store");

const ROOT_DIR = path.join(__dirname, "..");
const ZIPS_DIR = path.join(ROOT_DIR, "zips");
const OUT_FILE = path.join(ROOT_DIR, "js", "set-zips-data.js");

const ZIP_NAME_RE = /^(.*)-(hires|lowres)\.zip$/;

function scanStyle(style, folder) {
  const dir = path.join(ZIPS_DIR, folder);
  if (!fs.existsSync(dir)) return [];

  const out = [];
  for (const file of fs.readdirSync(dir)) {
    const match = file.match(ZIP_NAME_RE);
    if (!match) continue;
    const [, set, resolution] = match;
    const fullPath = path.join(dir, file);
    out.push({
      set,
      style,
      resolution,
      file: `${folder}/${file}`,
      bytes: fs.statSync(fullPath).size,
      count: readEntryCount(fullPath),
    });
  }
  return out;
}

function main() {
  const styles = getAllowedStyles();
  const rows = styles.flatMap((style) => scanStyle(style, folderNameForStyle(style)));

  if (rows.length === 0) {
    console.log(`No zips found under ${ZIPS_DIR}. Run \`npm run build-zips\` first.`);
  }

  const data = {};
  for (const row of rows) {
    data[row.set] ??= {};
    data[row.set][row.style] ??= {};
    data[row.set][row.style][row.resolution] = { file: row.file, bytes: row.bytes, count: row.count };
  }

  const sortedSets = Object.keys(data).sort((a, b) => a.localeCompare(b));
  const sortedData = {};
  sortedSets.forEach((set) => (sortedData[set] = data[set]));

  const contents = `// Generated by scripts/generate-set-zips-data.js — do not edit by hand.
// One entry per set, holding each style's hi-res/lo-res zip: file (relative to
// IMAGE_BASE_URL + "zips/"), byte size, and image count. Built by scanning zips/ —
// run \`npm run build-zips\` to (re)build the zips themselves after adding/changing
// set art, then \`npm run set-zips-data\` to regenerate this file.
const SET_ZIPS_DATA = ${JSON.stringify(sortedData, null, 2)};
`;

  fs.writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE} (${sortedSets.length} set(s), ${rows.length} zip(s)).`);
}

main();
