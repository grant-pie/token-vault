// Regenerates js/set-zips-data.js by scanning zips/<Style>/ for the *-hires.zip /
// *-lowres.zip (or, for sets big enough to trip the 300 MiB single-upload cap,
// *-hires-part1.zip, *-hires-part2.zip, ...) files written by build-set-zips.js. Run
// this after build-zips whenever the zips change, so sets.html has up-to-date
// filenames/sizes/counts to render download buttons from without hitting the network.
//
// Run: npm run set-zips-data

const fs = require("fs");
const path = require("path");
const { getAllowedStyles, folderNameForStyle } = require("./lib/styles");
const { readEntryCount } = require("./lib/zip-store");

const ROOT_DIR = path.join(__dirname, "..");
const ZIPS_DIR = path.join(ROOT_DIR, "zips");
const OUT_FILE = path.join(ROOT_DIR, "js", "set-zips-data.js");

// Captures the set name, resolution, and (if present) 1-based part number —
// unsuffixed files (no "-partN") are treated as a lone part 1.
const ZIP_NAME_RE = /^(.*)-(hires|lowres)(?:-part(\d+))?\.zip$/;

function scanStyle(style, folder) {
  const dir = path.join(ZIPS_DIR, folder);
  if (!fs.existsSync(dir)) return [];

  const out = [];
  for (const file of fs.readdirSync(dir)) {
    const match = file.match(ZIP_NAME_RE);
    if (!match) continue;
    const [, set, resolution, partNum] = match;
    const fullPath = path.join(dir, file);
    out.push({
      set,
      style,
      resolution,
      partIndex: partNum ? Number(partNum) : 1,
      // R2 keys the vault images by the lowercase style ("vault/standard/...",
      // see imageUrl() in js/vault.js) rather than the capitalized local disk
      // folder name ("Standard/") — zips follow the same convention, so `style`
      // (already lowercase) goes in the URL, even though `folder` (capitalized)
      // is what the file actually lives under on disk.
      file: `${style}/${file}`,
      bytes: fs.statSync(fullPath).size,
      count: readEntryCount(fullPath),
    });
  }
  return out;
}

function main() {
  const styles = getAllowedStyles();
  const rows = styles.flatMap((style) => scanStyle(style, folderNameForStyle(style)));

  if (rows.length === 0) {
    console.log(`No zips found under ${ZIPS_DIR}. Run \`npm run build-zips\` first.`);
  }

  const data = {};
  for (const row of rows) {
    data[row.set] ??= {};
    data[row.set][row.style] ??= {};
    data[row.set][row.style][row.resolution] ??= { parts: [] };
    data[row.set][row.style][row.resolution].parts.push({ index: row.partIndex, file: row.file, bytes: row.bytes, count: row.count });
  }

  // Sort each resolution's parts by index, then collapse into the shape the
  // frontend wants: an ordered parts array plus the resolution's total bytes/count.
  for (const bySet of Object.values(data)) {
    for (const byStyle of Object.values(bySet)) {
      for (const res of Object.values(byStyle)) {
        res.parts.sort((a, b) => a.index - b.index);
        res.parts = res.parts.map(({ file, bytes, count }) => ({ file, bytes, count }));
        res.bytes = res.parts.reduce((sum, p) => sum + p.bytes, 0);
        res.count = res.parts.reduce((sum, p) => sum + p.count, 0);
      }
    }
  }

  const sortedSets = Object.keys(data).sort((a, b) => a.localeCompare(b));
  const sortedData = {};
  sortedSets.forEach((set) => (sortedData[set] = data[set]));

  const contents = `// Generated by scripts/generate-set-zips-data.js — do not edit by hand.
// One entry per set, holding each style's hi-res/lo-res zip: "parts" (one or more
// { file, bytes, count } — more than one when the set was too big for a single
// upload, see build-set-zips.js), plus the resolution's total "bytes"/"count" across
// all parts. file is relative to IMAGE_BASE_URL + "zips/", with a lowercase style
// segment (e.g. "standard/Base Set 1-hires.zip") to match how images are keyed on R2
// (vault/standard/...) — upload zips/<Style>/ (capitalized, matching local disk) to
// a lowercase zips/<style>/ prefix on R2, same as images-optimized/<Style>/ already
// goes to vault/<style>/. Built by scanning zips/ — run \`npm run build-zips\` to
// (re)build the zips themselves after adding/changing set art, then
// \`npm run set-zips-data\` to regenerate this file.
const SET_ZIPS_DATA = ${JSON.stringify(sortedData, null, 2)};
`;

  fs.writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE} (${sortedSets.length} set(s), ${rows.length} zip file(s)).`);
}

main();
